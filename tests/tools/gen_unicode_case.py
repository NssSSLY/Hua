#!/usr/bin/env python3
"""Generates src/unicode_case_data.inc from the Unicode tables of the running Python.

  python tests/tools/gen_unicode_case.py > src/unicode_case_data.inc

Each mapping is {code point, target}. A target with bit 31 set is an index into
case_multi, which holds zero-padded sequences of up to 3 scalars. ASCII is left out:
the runtime handles it on a fast path. cased/ignorable are the Cased and Case_Ignorable
ranges the final sigma rule needs; Python exposes them only through str behaviour.
"""
import sys,unicodedata
scalars=[c for c in range(0x80,0x110000) if not 0xD800<=c<=0xDFFF]
multi=[];multi_index={}
def target(text):
    if len(text)==1:return f'{ord(text):#x}'
    key=tuple(map(ord,text))
    if key not in multi_index:
        multi_index[key]=len(multi);multi.append(key)
    return f'{0x80000000|multi_index[key]:#x}u'
def table(name,method):
    rows=[(c,method(chr(c))) for c in scalars]
    rows=[(c,t) for c,t in rows if t!=chr(c)]
    body=''.join(f'{{{c:#x},{target(t)}}},' for c,t in rows)
    return f'constexpr CaseMapping {name}[]={{{body}}};\n'
def final(prefix,c):return (prefix+chr(c)+'Σ').lower()[-1]=='ς'
def ranges(name,test):
    out=[];start=None
    for c in range(0x110000+1):
        hit=c<0x110000 and not 0xD800<=c<=0xDFFF and test(c)
        if hit and start is None:start=c
        if not hit and start is not None:out.append((start,c-1));start=None
    return f'constexpr CaseRange {name}[]={{'+''.join(f'{{{a:#x},{b:#x}}},' for a,b in out)+'};\n'
parts=[table('case_upper',str.upper),table('case_lower',str.lower),table('case_fold',str.casefold)]
parts.append(ranges('case_cased',lambda c:chr(c).islower() or chr(c).isupper() or chr(c).istitle()))
parts.append(ranges('case_ignorable',lambda c:final('A',c) and not final(' ',c)))
sys.stdout.write(f'// Generated by tests/tools/gen_unicode_case.py from Unicode {unicodedata.unidata_version}. Do not edit.\n')
sys.stdout.write(f'constexpr const char* case_unicode_version="{unicodedata.unidata_version}";\n')
sys.stdout.write('constexpr std::uint32_t case_multi[][3]={'+''.join('{'+','.join(f'{v:#x}' for v in (*m,0,0)[:3])+'},' for m in multi)+'};\n')
sys.stdout.write(''.join(parts))
